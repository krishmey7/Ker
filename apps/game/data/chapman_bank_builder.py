def _product_questions(
    template: str,
    spicy: int,
    category: str,
    seen: set[str],
    limit: int,
    **slots: list[str],
) -> list[dict]:
    """Combine des listes de mots dans une phrase complète unique."""
    keys = list(slots.keys())
    lists = [slots[k] for k in keys]
    out: list[dict] = []
    for combo in itertools.product(*lists):
        mapping = dict(zip(keys, combo))
        text = template.format(**mapping).strip()
        key = text.lower()
        if len(text) < 25 or key in seen:
            continue
        seen.add(key)
        out.append({"text": text, "category": category, "spicy_level": spicy})
        if len(out) >= limit:
            break
    return out


def _product_questions_grouped(
    template: str,
    spicy: int,
    category: str,
    seen: set[str],
    limit: int,
    **slot_groups: dict[str, list[str]],
) -> list[dict]:
    """Combine des groupes de mots cohérents pour éviter les associations incohérentes.
    
    slot_groups: {"slot_name": {"group_name": [items...]}}
    Exemple: {"lang": {"paroles": [...], "services": [...]}, "moment": {"positif": [...], "difficile": [...]}}
    """
    out: list[dict] = []
    
    # Générer toutes les combinaisons de groupes
    group_names = {slot: list(groups.keys()) for slot, groups in slot_groups.items()}
    group_keys = list(group_names.keys())
    
    for group_combo in itertools.product(*[group_names[k] for k in group_keys]):
        # Pour chaque combinaison de groupes, générer les combinaisons d'items
        selected_groups = dict(zip(group_keys, group_combo))
        current_slots = {slot: slot_groups[slot][selected_groups[slot]] for slot in group_keys}
        
        # Générer les questions pour cette combinaison de groupes
        batch = _product_questions(template, spicy, category, seen, limit - len(out), **current_slots)
        out.extend(batch)
        
        if len(out) >= limit:
            break
    
    return out


def _build_category(category: str, target: int, seen: set[str]) -> list[dict]:
    """Génère les questions uniquement depuis les anchors fixes (pas de combinaison)."""
    anchors = _BOOK_ANCHORS.get(category, [])
    out: list[dict] = []
    for text in anchors:
        key = text.lower()
        if key not in seen:
            seen.add(key)
            spicy = 1 if category == QuestionCategory.SPICY else 0
            out.append({"text": text, "category": category, "spicy_level": spicy})

    if len(out) < target:
        raise ValueError(
            f"Catégorie {category} : seulement {len(out)}/{target} questions "
            f"(ajoutez plus de questions fixes dans _BOOK_ANCHORS)."
        )
    return out[:target]


def generate_chapman_bank_questions() -> list[dict]:
    """1000 questions uniques, phrases complètes, esprit Gary Chapman."""
    seen: set[str] = set()
    all_questions: list[dict] = []

    for category, target in BANK_TARGETS.items():
        all_questions.extend(_build_category(category, target, seen))

    texts = [q["text"].lower() for q in all_questions]
    if len(all_questions) != 323:
        raise ValueError(f"Attendu 323 questions, obtenu {len(all_questions)}.")
    if len(set(texts)) != 323:
        dup = len(texts) - len(set(texts))
        raise ValueError(f"{dup} doublons détectés dans la banque.")
    return all_questions
